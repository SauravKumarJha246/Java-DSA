package first_classes;

public class increment_decrement {
    static void main() {
        int y = 5;
        System.out.println(y=y+6);
        System.out.println(y +=6);
        y *= 2;
        System.out.println(y);
        y -= 30;
        System.out.println(y);
        y ++; // y=y+1
        System.out.println(y);
        ++y;
        System.out.println(y);
        y--; // y=y-1
        System.out.println(y);
        --y;
        System.out.println(y);




    }


}
